import { useContext, useMemo, useState } from 'react'
import { ArrowRight, Bookmark, Download, FileText, Github, Globe2 } from 'lucide-react'
import { Link } from 'react-router-dom'
import { publicDevelopers } from '../data/developers'
import { SavedContext } from '../lib/community'

const profileId = (name: string) => name.toLowerCase().replace(/ /g, '-')

export default function ForTeams() {
  const { savedIds, savedPostIds, posts, toggleSaved, toggleSavedPost } = useContext(SavedContext)
  const [downloaded, setDownloaded] = useState(false)
  const savedPeople = useMemo(() => publicDevelopers.filter(person => savedIds.includes(person.id ?? profileId(person.name))), [savedIds])
  const savedPosts = useMemo(() => posts.filter(post => savedPostIds.includes(post.id)), [posts, savedPostIds])
  const missingProfiles = Math.max(0, savedIds.length - savedPeople.length)

  function downloadBrief() {
    const lines = ['# DevDirectory team shortlist', '', `Exported ${new Date().toLocaleDateString()}`, '', `## Developers (${savedPeople.length})`, '']
    if (!savedPeople.length) lines.push('_No public developer profiles saved yet._', '')
    savedPeople.forEach(person => {
      lines.push(`### ${person.name}`, '', `- ${person.role}`, `- ${person.company ? `Organization: ${person.company}` : `Location: ${person.location}`}`, `- Skills: ${person.skills.join(', ')}`)
      if (person.github) lines.push(`- GitHub: ${person.github}`)
      if (person.website) lines.push(`- Website: ${person.website}`)
      lines.push('', person.bio, '')
    })
    lines.push(`## Saved posts (${savedPosts.length})`, '')
    if (!savedPosts.length) lines.push('_No posts saved yet._', '')
    savedPosts.forEach(post => lines.push(`### ${post.title}`, '', `By ${post.authorName} · ${new Date(post.createdAt).toLocaleDateString()}`, '', post.body, ''))
    if (missingProfiles) lines.push(`_${missingProfiles} saved profile(s) are not included because they are not part of the public sample directory._`, '')
    lines.push('---', 'Generated by DevDirectory. Public profiles are references, not verified team members.')
    const blob = new Blob([lines.join('\n')], { type: 'text/markdown;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const anchor = document.createElement('a')
    anchor.href = url
    anchor.download = 'devdirectory-team-shortlist.md'
    anchor.click()
    window.setTimeout(() => URL.revokeObjectURL(url), 1000)
    setDownloaded(true)
  }

  return <main className="directory page-shell teams-page" data-reveal>
    <div className="eyebrow"><span className="eyebrow-line" /> FOR ENGINEERING TEAMS</div>
    <h1>Turn good finds into <span>a team brief.</span></h1>
    <p className="directory-intro">Collect public developer profiles and useful posts, then export one concise Markdown brief to share with your team.</p>
    <section className="team-tool-summary" aria-label="Shortlist totals">
      <div><strong>{savedPeople.length}</strong><span>Saved public profiles</span></div>
      <div><strong>{savedPosts.length}</strong><span>Saved posts</span></div>
      <div><strong>{savedIds.length + savedPostIds.length}</strong><span>Saved items total</span></div>
      <button className="button" onClick={downloadBrief}><Download size={15} /> Export team brief</button>
    </section>
    {downloaded && <p className="form-feedback form-success" role="status">Your Markdown team brief has been downloaded.</p>}
    <section className="team-shortlist-section">
      <div className="team-section-heading"><div><span className="eyebrow"><span className="eyebrow-line" /> YOUR SHORTLIST</span><h2>People to revisit</h2></div><Link className="text-link" to="/developers">Find more people <ArrowRight size={14} /></Link></div>
      {savedPeople.length ? <div className="team-saved-people">{savedPeople.map(person => <article className="team-saved-person" key={person.name}>
        <img src={person.image} alt="" loading="lazy" onError={event => { event.currentTarget.style.display = 'none' }} />
        <div className="team-saved-copy"><h3>{person.name}</h3><p>{person.role}{person.company ? ` · ${person.company}` : ''}</p><div className="skill-list">{person.skills.map(skill => <span key={skill}>{skill}</span>)}</div></div>
        <div className="team-saved-actions">{person.github && <a href={person.github} target="_blank" rel="noreferrer" aria-label={`Open ${person.name}'s GitHub`}><Github size={15} /></a>}{person.website && <a href={person.website} target="_blank" rel="noreferrer" aria-label={`Open ${person.name}'s website`}><Globe2 size={15} /></a>}<Link to={`/developers/${profileId(person.name)}`} aria-label={`View ${person.name}'s profile`}><ArrowRight size={15} /></Link><button onClick={() => toggleSaved(profileId(person.name))} aria-label={`Remove ${person.name} from shortlist`}><Bookmark size={15} fill="currentColor" /></button></div>
      </article>)}</div> : <div className="team-empty"><Bookmark size={20} /><p>Your shortlist is empty. Save developers from the directory and they’ll appear here.</p><Link to="/developers" className="button button-quiet">Browse developers <ArrowRight size={14} /></Link></div>}
      {missingProfiles > 0 && <p className="muted-small">{missingProfiles} saved profile(s) belong to a connected workspace and aren’t available in this local preview.</p>}
    </section>
    <section className="team-shortlist-section team-posts-section"><div className="team-section-heading"><div><span className="eyebrow"><span className="eyebrow-line" /> SAVED READING</span><h2>Posts for the conversation</h2></div><Link className="text-link" to="/add-post">Write an update <ArrowRight size={14} /></Link></div>
      {savedPosts.length ? <div className="team-saved-posts">{savedPosts.map(post => <article className="community-post" key={post.id}><FileText size={17} /><div><span className="post-date">{post.authorName} · {new Date(post.createdAt).toLocaleDateString()}</span><h3>{post.title}</h3><p>{post.body}</p></div><button className="delete-button" onClick={() => toggleSavedPost(post.id)} aria-label={`Remove ${post.title} from saved posts`}><Bookmark size={15} fill="currentColor" /></button></article>)}</div> : <p className="muted-small">No posts saved yet. Bookmark a post from a developer profile to include it in your brief.</p>}
    </section>
    <p className="team-data-note">Your bookmarks are stored in this browser. This preview does not sync a shared team account; export the brief to pass your shortlist along.</p>
  </main>
}
